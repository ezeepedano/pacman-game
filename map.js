class Map {
    constructor() {
        this.tiles = [];
        this.dotsCount = 0;
        this.wallColor = LEVEL_COLORS[0];
        this.init(0);
    }

    init(levelIndex) {
        // Handle repeating or default levels if index is out of bounds
        const rawLevel = levels[levelIndex % levels.length];
        this.wallColor = LEVEL_COLORS[levelIndex % LEVEL_COLORS.length];

        this.tiles = [];
        this.dotsCount = 0;

        for (let row = 0; row < MAP_HEIGHT; row++) {
            this.tiles[row] = [];
            for (let col = 0; col < MAP_WIDTH; col++) {
                // If the predefined level doesn't reach MAP_HEIGHT, fill with empty space or walls depending on boundary
                let tileType = TILE.EMPTY;
                if (row < rawLevel.length && col < rawLevel[row].length) {
                    tileType = rawLevel[row][col];
                } else if (row === 0 || row === MAP_HEIGHT - 1 || col === 0 || col === MAP_WIDTH - 1) {
                     tileType = TILE.WALL;
                }

                this.tiles[row][col] = tileType;

                if (tileType === TILE.DOT || tileType === TILE.POWER_PILL || tileType === TILE.POWER_SPEED || tileType === TILE.POWER_FREEZE) {
                    this.dotsCount++;
                }
            }
        }
    }

    isWall(col, row) {
        if (col < 0 || col >= MAP_WIDTH || row < 0 || row >= MAP_HEIGHT) {
            return false; // Tunnel edges are handled separately
        }
        return this.tiles[row][col] === TILE.WALL;
    }

    isGhostDoor(col, row) {
        if (col < 0 || col >= MAP_WIDTH || row < 0 || row >= MAP_HEIGHT) {
            return false;
        }
        return this.tiles[row][col] === TILE.GHOST_DOOR;
    }

    eatDot(col, row) {
        if (col < 0 || col >= MAP_WIDTH || row < 0 || row >= MAP_HEIGHT) {
            return null;
        }
        const tile = this.tiles[row][col];
        if (tile === TILE.DOT || tile === TILE.POWER_PILL || tile === TILE.POWER_SPEED || tile === TILE.POWER_FREEZE) {
            this.tiles[row][col] = TILE.EMPTY;
            this.dotsCount--;
            return tile;
        }
        return null;
    }

    draw(ctx) {
        for (let row = 0; row < MAP_HEIGHT; row++) {
            for (let col = 0; col < MAP_WIDTH; col++) {
                const x = col * TILE_SIZE;
                const y = row * TILE_SIZE;
                const tile = this.tiles[row][col];

                if (tile === TILE.WALL) {
                    ctx.fillStyle = this.wallColor;
                    ctx.fillRect(x, y, TILE_SIZE, TILE_SIZE);
                    ctx.strokeStyle = 'black';
                    ctx.strokeRect(x, y, TILE_SIZE, TILE_SIZE);
                } else if (tile === TILE.DOT) {
                    ctx.fillStyle = 'white';
                    ctx.beginPath();
                    ctx.arc(x + TILE_SIZE / 2, y + TILE_SIZE / 2, 3, 0, Math.PI * 2);
                    ctx.fill();
                } else if (tile === TILE.POWER_PILL) {
                    ctx.fillStyle = 'white';
                    ctx.beginPath();
                    ctx.arc(x + TILE_SIZE / 2, y + TILE_SIZE / 2, 8, 0, Math.PI * 2);
                    ctx.fill();
                } else if (tile === TILE.GHOST_DOOR) {
                    ctx.fillStyle = 'pink';
                    ctx.fillRect(x, y + TILE_SIZE / 2 - 2, TILE_SIZE, 4);
                } else if (tile === TILE.POWER_SPEED) {
                    ctx.fillStyle = 'yellow'; // Speed power-up
                    ctx.beginPath();
                    ctx.moveTo(x + TILE_SIZE / 2, y + 2);
                    ctx.lineTo(x + TILE_SIZE - 2, y + TILE_SIZE - 2);
                    ctx.lineTo(x + 2, y + TILE_SIZE - 2);
                    ctx.fill();
                } else if (tile === TILE.POWER_FREEZE) {
                    ctx.fillStyle = 'cyan'; // Freeze power-up
                    ctx.fillRect(x + 4, y + 4, TILE_SIZE - 8, TILE_SIZE - 8);
                }
            }
        }
    }
}